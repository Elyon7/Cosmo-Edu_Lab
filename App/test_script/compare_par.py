def parse_scientific(val_str):
    val_str = val_str.replace('\\\\', '').replace('$', '').strip()
    if val_str == '--' or val_str == '' or 'textbf' in val_str:
        return np.nan
    if '\\times 10^{' in val_str:
        base, exp = val_str.split('\\times 10^{')
        exp = exp.replace('}', '')
        return float(base) * (10**float(exp))
    return float(val_str)

def extract_data(latex_text):
    lines = latex_text.strip().split('\n')
    data = {}
    current_galaxy = None
    
    for line in lines:
        if 'multirow' in line:
            match = re.search(r'\\multirow\{\d+\}\{\*\}\{\\textbf\{([^}]+)\}\}', line)
            if match:
                current_galaxy = match.group(1)
            if '&' not in line:
                continue
            
        if '&' not in line or 'multicolumn' in line or 'textbf{Galaxy}' in line:
            continue
            
        if not current_galaxy:
            continue
            
        parts = [p.strip() for p in line.split('&')]
        method = parts[1].replace('$', '').strip()
        
        if current_galaxy not in data:
            data[current_galaxy] = {}
            
        data[current_galaxy][method] = {
            'upsilon': parse_scientific(parts[2]),
            'rs': parse_scientific(parts[3]),
            'rhos': parse_scientific(parts[4]),
            'chi2': parse_scientific(parts[5]),
            'm200': parse_scientific(parts[6])
        }
    return data

def pct_diff(val, ref):
    if np.isnan(val) or np.isnan(ref) or ref == 0:
        return np.nan
    return abs(val - ref) / ref * 100.0

def format_val(val, is_mass_or_rho=False):
    """Formatta i numeri in modo compatto per non sbordare dalla pagina LaTeX"""
    if np.isnan(val): return "--"
    
    # Se è una percentuale di outlier altissima o una massa
    if is_mass_or_rho and (val > 1000 or val < 0.01):
        s = f"{val:.2e}".replace('e+0', ' \\times 10^{').replace('e+', ' \\times 10^{').replace('e-0', ' \\times 10^{-').replace('e-', ' \\times 10^{-')
        # Chiude la parentesi graffa dell'esponente
        if '\\times' in s:
            s += "}"
        return f"${s}$"
    
    return f"{val:.2f}"

